// MessagesLogPath 主代理对话日志路径（快照式覆盖写入）。
var MessagesLogPath = "messages.json"

// SubMessagesLogPath 子代理（subagent）对话日志路径。
var SubMessagesLogPath = "messages-sub.json"

// ReadlineHistoryPath readline 命令历史文件（↑↓ 翻页、跨进程保留）。
var ReadlineHistoryPath = ".coding-agent-history"

// appLogPath 运行诊断日志（append 模式，进程退出后保留，用于定位异常退出）。
var appLogPath = "coding-agent-go.log"

// AppLog 默认丢弃输出：测试不调用 InitLogger 也安全。每条记录直接写文件、
// 无缓冲，进程崩溃前写入的日志不会丢。
var AppLog = slog.New(&bracketHandler{w: io.Discard, mu: &sync.Mutex{}, level: slog.LevelInfo})

// InitLogger 以 append 模式打开日志文件并替换全局 logger；文件句柄跟随进程生命周期，
// 不主动 close。
func InitLogger() error {
	f, err := os.OpenFile(appLogPath, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return err
	}
	AppLog = slog.New(&bracketHandler{w: f, mu: &sync.Mutex{}, level: slog.LevelInfo})
	return nil
}

// bracketHandler 以 "[时间戳][级别] [调用点] 消息 key=value" 格式输出日志，时间戳为本地时间。
type bracketHandler struct {
	w     io.Writer
	mu    *sync.Mutex
	level slog.Level
	attrs []slog.Attr
}

func (h *bracketHandler) Enabled(_ context.Context, l slog.Level) bool {
	return l >= h.level
}

func (h *bracketHandler) Handle(_ context.Context, r slog.Record) error {
	var buf bytes.Buffer
	buf.WriteByte('[')
	buf.WriteString(r.Time.Format("2006-01-02 15:04:05.000"))
	buf.WriteString("][")
	buf.WriteString(levelName(r.Level))
	buf.WriteString("] ")

	// 添加调用点信息（文件名和行号）
	if caller := getCaller(); caller != "" {
		buf.WriteString(caller)
		buf.WriteString(" ")
	}

	buf.WriteString(r.Message)
	writeAttr := func(a slog.Attr) {
		buf.WriteByte(' ')
		buf.WriteString(a.Key)
		buf.WriteByte('=')
		buf.WriteString(a.Value.String())
	}
	for _, a := range h.attrs {
		writeAttr(a)
	}
	r.Attrs(func(a slog.Attr) bool {
		writeAttr(a)
		return true
	})
	buf.WriteByte('\n')

	h.mu.Lock()
	defer h.mu.Unlock()
	_, err := h.w.Write(buf.Bytes())
	return err
}

func (h *bracketHandler) WithAttrs(attrs []slog.Attr) slog.Handler {
	nh := *h
	nh.attrs = append(append([]slog.Attr{}, h.attrs...), attrs...)
	return &nh
}

func (h *bracketHandler) WithGroup(string) slog.Handler { return h }

// levelName 输出首字母大写的级别名：Info / Warn / Error / Debug。
func levelName(l slog.Level) string {
	switch {
	case l >= slog.LevelError:
		return "Error"
	case l >= slog.LevelWarn:
		return "Warn"
	case l >= slog.LevelInfo:
		return "Info"
	default:
		return "Debug"
	}
}

// getCaller 返回调用点的文件名和行号，格式为 [file.go:line]。
// 跳过 runtime 和 logging 包本身的帧，找到第一个业务调用点。
func getCaller() string {
	pc := make([]uintptr, 20)
	n := runtime.Callers(2, pc)
	if n == 0 {
		return ""
	}

	frames := runtime.CallersFrames(pc[:n])
	for {
		frame, more := frames.Next()
		// 跳过 runtime、log/slog 标准库和 logging.go 本身的帧。
		// 若不跳过 log/slog，报出的会是 logger.go 内部行号而非业务调用点。
		if frame.Function == "runtime.goexit" ||
			frame.Function == "runtime.main" ||
			frame.File == "<autogenerated>" ||
			strings.HasPrefix(frame.Function, "log/slog") ||
			strings.Contains(frame.File, "/log/slog/") {
			if !more {
				break
			}
			continue
		}
		// 找到第一个非 logging.go 的调用点
		if frame.File != "" && !isLoggingFile(frame.File) {
			// 只取文件名，不取完整路径
			shortFile := frame.File
			for i := len(shortFile) - 1; i >= 0; i-- {
				if shortFile[i] == '/' {
					shortFile = shortFile[i+1:]
					break
				}
			}
			return fmt.Sprintf("[%s:%d]", shortFile, frame.Line)
		}
		if !more {
			break
		}
	}
	return ""
}

// isLoggingFile 判断文件是否是 logging.go 或 log.go（本包自身文件）。
func isLoggingFile(file string) bool {
	base := file
	for i := len(file) - 1; i >= 0; i-- {
		if file[i] == '/' {
			base = file[i+1:]
			break
		}
	}
	return base == "logging.go" || base == "log.go"
}

// TruncateForLog 截断字符串用于日志输出，避免日志文件过大。
// 超过 maxLen 字符时截断并添加 "...(truncated)" 后缀。
// 同时将换行符转义，保证日志单行输出。
func TruncateForLog(s string) string {
	const maxLen = 500
	// 先转义换行符，保证单行输出
	s = escapeNewlines(s)
	if len(s) <= maxLen {
		return s
	}
	// 按字符截断（支持 UTF-8）
	runes := []rune(s)
	if len(runes) <= maxLen {
		return s
	}
	return string(runes[:maxLen]) + "...(truncated)"
}

// escapeNewlines 将字符串中的换行符转义为 \n，保证日志单行输出。
func escapeNewlines(s string) string {
	// 替换 \r\n 和 \n
	s = strings.ReplaceAll(s, "\r\n", `\n`)
	s = strings.ReplaceAll(s, "\n", `\n`)
	s = strings.ReplaceAll(s, "\r", `\r`)
	return s
}

// LogTurnSummary 打印每轮对话的请求摘要：system prompt 长度 + 最后一条 user message 内容。
func LogTurnSummary(turn int, phase string, sysPrompt string, messages []anthropic.MessageParam) {
	// 提取最后一条 user message
	var lastUserMsg string
	for i := len(messages) - 1; i >= 0; i-- {
		if messages[i].Role == anthropic.MessageParamRoleUser {
			for _, block := range messages[i].Content {
				if block.OfText != nil {
					lastUserMsg = block.OfText.Text
					break
				} else if block.OfToolResult != nil {
					// 提取 tool_result 的内容
					for _, content := range block.OfToolResult.Content {
						if content.OfText != nil {
							lastUserMsg = fmt.Sprintf("<tool_result>%s</tool_result>", content.OfText.Text)
							break
						}
					}
					if lastUserMsg != "" {
						break
					}
				}
			}
			if lastUserMsg != "" {
				break
			}
		}
	}

	AppLog.Info("turn summary",
		"turn", turn,
		"phase", phase,
		"system_prompt_chars", len(sysPrompt),
		"messages_count", len(messages),
		"last_user_message", TruncateForLog(lastUserMsg))
}

// LogModelResponse 打印模型回答的摘要：思考内容 + 文本内容 + 工具调用列表。
func LogModelResponse(turn int, resp *anthropic.Message) {
	var thinkingContent string
	var textContent string
	var toolCalls []string

	for _, block := range resp.Content {
		switch block.Type {
		case "thinking":
			thinkingContent += block.Thinking
		case "text":
			textContent += block.Text
		case "tool_use":
			toolCalls = append(toolCalls, fmt.Sprintf("%s(%s)", block.Name, TruncateForLog(string(block.Input))))
		case "server_tool_use":
			// 服务端工具调用（web_search / web_fetch 由百炼服务端执行）
			stu := block.AsServerToolUse()
			toolCalls = append(toolCalls, fmt.Sprintf("server:%s(%v)", stu.Name, TruncateForLog(fmt.Sprintf("%v", stu.Input))))
		}
	}

	// 记录完整的模型回答，包括思考、文本和工具调用
	if thinkingContent != "" {
		AppLog.Info("model response",
			"turn", turn,
			"thinking", TruncateForLog(thinkingContent),
			"text", TruncateForLog(textContent),
			"tool_calls", strings.Join(toolCalls, "; "))
	} else {
		AppLog.Info("model response",
			"turn", turn,
			"text", TruncateForLog(textContent),
			"tool_calls", strings.Join(toolCalls, "; "))
	}
}

// ResetLogs 快照日志：每次调用覆盖写入，启动时置空对象即可。
func ResetLogs() error {
	if err := os.WriteFile(MessagesLogPath, []byte("{}"), 0o644); err != nil {
		return err
	}
	return os.WriteFile(SubMessagesLogPath, []byte("{}"), 0o644)
}

// LogMessages 覆盖写入主代理的完整会话快照到 MessagesLogPath。
func LogMessages(turn int, systemPrompt string, messages []anthropic.MessageParam) {
	writeMessagesLog(MessagesLogPath, turn, systemPrompt, messages)
}

// LogSubMessages 覆盖写入子代理的完整会话快照到 SubMessagesLogPath。
func LogSubMessages(turn int, systemPrompt string, messages []anthropic.MessageParam) {
	writeMessagesLog(SubMessagesLogPath, turn, systemPrompt, messages)
}

// writeMessagesLog 覆盖写入当前完整会话快照：system prompt（作为 role=system 消息）+
// 用户输入 + 模型回答 + tool_use/tool_result。react 模式下 messages 本身已包含
// 全部历史，覆盖而非追加可避免历史重复。
func writeMessagesLog(path string, turn int, systemPrompt string, messages []anthropic.MessageParam) {
	// 将 system prompt 作为第一条消息前置，保证日志是模型的完整输入。
	fullMessages := make([]anthropic.MessageParam, 0, 1+len(messages))
	if systemPrompt != "" {
		fullMessages = append(fullMessages, anthropic.MessageParam{
			Role:    anthropic.MessageParamRoleSystem,
			Content: []anthropic.ContentBlockParamUnion{anthropic.NewTextBlock(systemPrompt)},
		})
	}
	fullMessages = append(fullMessages, messages...)

	entry := map[string]any{
		"ts":       time.Now().UTC().Format(time.RFC3339Nano),
		"turn":     turn,
		"messages": fullMessages,
	}

	// SDK 的 tool_use input 是 json.RawMessage（API 响应原文，服务端含 &<>
	// 的 \uXXXX 转义），直接 Encode 会原样透传。先序列化再反序列化为 any 做
	// 归一化，之后重新编码即为可读原文。
	raw, err := json.Marshal(entry)
	if err != nil {
		fmt.Fprintf(os.Stderr, "warning: log messages: %v\n", err)
		return
	}
	var normalized any
	if err := json.Unmarshal(raw, &normalized); err != nil {
		fmt.Fprintf(os.Stderr, "warning: log messages: %v\n", err)
		return
	}

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(normalized); err != nil {
		fmt.Fprintf(os.Stderr, "warning: log messages: %v\n", err)
		return
	}
	if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "warning: log messages: %v\n", err)
	}
}
